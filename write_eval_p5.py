#!/usr/bin/env python3
"""Append mobility + stage 5 + scoring to eval.cpp."""

lines = []
lines.append('')
lines.append('    if (stage >= 4) {')
lines.append('        Bitboard occ = occ_all(b);')
lines.append('        Bitboard b_pawn_atk = 0;')
lines.append('        Bitboard bp2 = b.pieces[BLACK][PAWN];')
lines.append('        while (bp2) b_pawn_atk |= pawn_attacks[BLACK][pop_lsb(bp2)];')
lines.append('        Bitboard w_pawn_atk = 0;')
lines.append('        Bitboard wp2 = b.pieces[WHITE][PAWN];')
lines.append('        while (wp2) w_pawn_atk |= pawn_attacks[WHITE][pop_lsb(wp2)];')
lines.append('')
lines.append('        Bitboard wmob = 0;')
lines.append('        Bitboard bb = b.pieces[WHITE][KNIGHT];')
lines.append('        while (bb) wmob |= knight_attacks[pop_lsb(bb)];')
lines.append('        bb = b.pieces[WHITE][BISHOP];')
lines.append('        while (bb) wmob |= bishop_attacks(pop_lsb(bb), occ);')
lines.append('        bb = b.pieces[WHITE][ROOK];')
lines.append('        while (bb) wmob |= rook_attacks(pop_lsb(bb), occ);')
lines.append('        bb = b.pieces[WHITE][QUEEN];')
lines.append('        while (bb) wmob |= queen_attacks(pop_lsb(bb), occ);')
lines.append('        wmob &= ~b.occ[WHITE];')
lines.append('        wmob &= ~b_pawn_atk;')
lines.append('')
lines.append('        Bitboard bmob = 0;')
lines.append('        bb = b.pieces[BLACK][KNIGHT];')
lines.append('        while (bb) bmob |= knight_attacks[pop_lsb(bb)];')
lines.append('        bb = b.pieces[BLACK][BISHOP];')
lines.append('        while (bb) bmob |= bishop_attacks(pop_lsb(bb), occ);')
lines.append('        bb = b.pieces[BLACK][ROOK];')
lines.append('        while (bb) bmob |= rook_attacks(pop_lsb(bb), occ);')
lines.append('        bb = b.pieces[BLACK][QUEEN];')
lines.append('        while (bb) bmob |= queen_attacks(pop_lsb(bb), occ);')
lines.append('        bmob &= ~b.occ[BLACK];')
lines.append('        bmob &= ~w_pawn_atk;')
lines.append('')
lines.append('        int wcount = int(popcount(wmob));')
lines.append('        int bcount = int(popcount(bmob));')
lines.append('        mg += (wcount - bcount) * C.mobility_mg;')
lines.append('        eg += (wcount - bcount) * C.mobility_eg;')
lines.append('    }')
lines.append('')
lines.append('    if (stage >= 5) {')
lines.append('        if (popcount(b.pieces[WHITE][BISHOP]) >= 2) { mg += C.bishop_pair_mg; eg += C.bishop_pair_eg; }')
lines.append('        if (popcount(b.pieces[BLACK][BISHOP]) >= 2) { mg -= C.bishop_pair_mg; eg -= C.bishop_pair_eg; }')
lines.append('')
lines.append('        Bitboard wp = b.pieces[WHITE][PAWN];')
lines.append('        Bitboard bp = b.pieces[BLACK][PAWN];')
lines.append('        for (int f = 0; f < 8; ++f) {')
lines.append('            Bitboard fm = file_mask[f];')
lines.append('            bool w_p = (wp & fm) != 0;')
lines.append('            bool b_p = (bp & fm) != 0;')
lines.append('            if (!w_p && !b_p) {')
lines.append('                if (b.pieces[WHITE][ROOK] & fm) { mg += C.open_file_mg; eg += C.open_file_eg; }')
lines.append('                if (b.pieces[WHITE][QUEEN] & fm) { mg += C.open_file_mg / 2; eg += C.open_file_eg / 2; }')
lines.append('                if (b.pieces[BLACK][ROOK] & fm) { mg -= C.open_file_mg; eg -= C.open_file_eg; }')
lines.append('                if (b.pieces[BLACK][QUEEN] & fm) { mg -= C.open_file_mg / 2; eg -= C.open_file_eg / 2; }')
lines.append('            } else if (!w_p && b_p) {')
lines.append('                if (b.pieces[WHITE][ROOK] & fm) { mg += C.semi_open_file_mg; eg += C.semi_open_file_eg; }')
lines.append('                if (b.pieces[WHITE][QUEEN] & fm) { mg += C.semi_open_file_mg / 2; eg += C.semi_open_file_eg / 2; }')
lines.append('            } else if (w_p && !b_p) {')
lines.append('                if (b.pieces[BLACK][ROOK] & fm) { mg -= C.semi_open_file_mg; eg -= C.semi_open_file_eg; }')
lines.append('                if (b.pieces[BLACK][QUEEN] & fm) { mg -= C.semi_open_file_mg / 2; eg -= C.semi_open_file_eg / 2; }')
lines.append('            }')
lines.append('        }')
lines.append('')
lines.append('        Bitboard rank7 = 0xFFULL << 48;')
lines.append('        Bitboard rank2 = 0xFFULL << 8;')
lines.append('        if (b.pieces[WHITE][ROOK] & rank7) { mg += C.seventh_rank_mg; eg += C.seventh_rank_eg; }')
lines.append('        if (b.pieces[WHITE][QUEEN] & rank7) { mg += C.seventh_rank_mg; eg += C.seventh_rank_eg; }')
lines.append('        if (b.pieces[BLACK][ROOK] & rank2) { mg -= C.seventh_rank_mg; eg -= C.seventh_rank_eg; }')
lines.append('        if (b.pieces[BLACK][QUEEN] & rank2) { mg -= C.seventh_rank_mg; eg -= C.seventh_rank_eg; }')
lines.append('')
lines.append('        int ws = int(popcount(wp & shelter_mask[WHITE][b.king_sq[WHITE]]));')
lines.append('        int bs = int(popcount(bp & shelter_mask[BLACK][b.king_sq[BLACK]]));')
lines.append('        mg += ws * C.king_shield_mg;')
lines.append('        mg -= bs * C.king_shield_mg;')
lines.append('')
lines.append('        eg += (6 - CENTER_DIST[b.king_sq[WHITE]]) * C.king_center_eg;')
lines.append('        eg -= (6 - CENTER_DIST[mirror_sq(b.king_sq[BLACK])]) * C.king_center_eg;')
lines.append('    }')
lines.append('')
lines.append('    int score = (mg * phase + eg * (GAME_PHASE_MAX - phase)) / GAME_PHASE_MAX;')
lines.append('    if (stage >= 6)')
lines.append('        score += C.tempo;')
lines.append('    return b.side == WHITE ? score : -score;')
lines.append('}')
lines.append('')
lines.append('} // namespace kana')

with open(r'c:\Users\tahae\Kanamecide\src\eval.cpp', 'a') as f:
    f.write('\n'.join(lines))
print('Part 5 written')
