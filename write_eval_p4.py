#!/usr/bin/env python3
"""Append evaluate() to eval.cpp."""

lines = []
lines.append('// ---------------------------------------------------------------------------')
lines.append('// evaluate')
lines.append('// ---------------------------------------------------------------------------')
lines.append('int evaluate(const Board& b) {')
lines.append('    if (stage == 0) {')
lines.append('        int score = 0;')
lines.append('        for (int pt = 0; pt < PIECE_TYPE_NB; ++pt)')
lines.append('            score += FLAT_VALUE[pt] * int(popcount(b.pieces[WHITE][pt]) - popcount(b.pieces[BLACK][pt]));')
lines.append('        return b.side == WHITE ? score : -score;')
lines.append('    }')
lines.append('')
lines.append('    int phase = 0;')
lines.append('    phase += int(popcount(b.pieces[WHITE][KNIGHT] | b.pieces[BLACK][KNIGHT])) * 1;')
lines.append('    phase += int(popcount(b.pieces[WHITE][BISHOP] | b.pieces[BLACK][BISHOP])) * 1;')
lines.append('    phase += int(popcount(b.pieces[WHITE][ROOK]   | b.pieces[BLACK][ROOK]))   * 2;')
lines.append('    phase += int(popcount(b.pieces[WHITE][QUEEN]  | b.pieces[BLACK][QUEEN]))  * 4;')
lines.append('    phase = std::min(phase, GAME_PHASE_MAX);')
lines.append('')
lines.append('    int mg = 0, eg = 0;')
lines.append('')
lines.append('    for (int pt = PAWN; pt <= QUEEN; ++pt) {')
lines.append('        int diff = int(popcount(b.pieces[WHITE][pt]) - popcount(b.pieces[BLACK][pt]));')
lines.append('        mg += diff * C.mg_value[pt];')
lines.append('        eg += diff * C.eg_value[pt];')
lines.append('    }')
lines.append('')
lines.append('    if (stage >= 2) {')
lines.append('        for (Square s = A1; s < SQ_NB; s = Square(s + 1)) {')
lines.append('            int pc = b.mailbox[s];')
lines.append('            if (pc == 0) continue;')
lines.append('            Color c = piece_color(pc);')
lines.append('            PieceType pt = piece_type(pc);')
lines.append('            if (c == WHITE) {')
lines.append('                mg += C.mg_pst[pt][s];')
lines.append('                eg += C.eg_pst[pt][s];')
lines.append('            } else {')
lines.append('                Square ms = mirror_sq(s);')
lines.append('                mg -= C.mg_pst[pt][ms];')
lines.append('                eg -= C.eg_pst[pt][ms];')
lines.append('            }')
lines.append('        }')
lines.append('    }')
lines.append('')
lines.append('    if (stage >= 3) {')
lines.append('        Bitboard wp = b.pieces[WHITE][PAWN];')
lines.append('        Bitboard bp = b.pieces[BLACK][PAWN];')
lines.append('        for (int f = 0; f < 8; ++f) {')
lines.append('            Bitboard fm = file_mask[f];')
lines.append('            int wc = int(popcount(wp & fm));')
lines.append('            int bc = int(popcount(bp & fm));')
lines.append('            if (wc >= 2) { mg += (wc - 1) * C.doubled_pawn_mg; eg += (wc - 1) * C.doubled_pawn_eg; }')
lines.append('            if (bc >= 2) { mg -= (bc - 1) * C.doubled_pawn_mg; eg -= (bc - 1) * C.doubled_pawn_eg; }')
lines.append('            if ((wp & fm) && !(wp & (adj_file_mask[f] ^ fm))) {')
lines.append('                int cnt = int(popcount(wp & fm));')
lines.append('                mg += cnt * C.isolated_pawn_mg;')
lines.append('                eg += cnt * C.isolated_pawn_eg;')
lines.append('            }')
lines.append('            if ((bp & fm) && !(bp & (adj_file_mask[f] ^ fm))) {')
lines.append('                int cnt = int(popcount(bp & fm));')
lines.append('                mg -= cnt * C.isolated_pawn_mg;')
lines.append('                eg -= cnt * C.isolated_pawn_eg;')
lines.append('            }')
lines.append('        }')
lines.append('        Bitboard wpp = wp;')
lines.append('        while (wpp) {')
lines.append('            Square s = pop_lsb(wpp);')
lines.append('            if (!(bp & passed_mask[WHITE][s])) {')
lines.append('                int r = rank_of(s);')
lines.append('                mg += C.passed_pawn_mg[r];')
lines.append('                eg += C.passed_pawn_eg[r];')
lines.append('            }')
lines.append('        }')
lines.append('        Bitboard bpp = bp;')
lines.append('        while (bpp) {')
lines.append('            Square s = pop_lsb(bpp);')
lines.append('            if (!(wp & passed_mask[BLACK][s])) {')
lines.append('                int r = 7 - rank_of(s);')
lines.append('                mg -= C.passed_pawn_mg[r];')
lines.append('                eg -= C.passed_pawn_eg[r];')
lines.append('            }')
lines.append('        }')
lines.append('    }')

with open(r'c:\Users\tahae\Kanamecide\src\eval.cpp', 'a') as f:
    f.write('\n'.join(lines))
print('Part 4 written')
